class I18nManager(QObject):
    language_changed = pyqtSignal()

    def __init__(self):
        super().__init__()
        self._current_lang = "ko"

    def detect_os_language(self):
        sys_lang = QLocale.system().name()
        if sys_lang.startswith("en"):
            self.set_language("en")
        elif sys_lang.startswith("ja"):
            self.set_language("ja")
        elif sys_lang == "zh_CN" or sys_lang.startswith("zh_Hans"):
            self.set_language("zh_CN")
        elif sys_lang.startswith("zh"):
            self.set_language("zh_TW")
        else:
            self.set_language("ko")

    def set_language(self, lang_code):
        if lang_code in TRANSLATIONS and self._current_lang != lang_code:
            self._current_lang = lang_code
            self.language_changed.emit()

    def get_lang(self):
        return self._current_lang

    def tr(self, key):
        return TRANSLATIONS.get(self._current_lang, TRANSLATIONS["ko"]).get(key, key)

I18n = I18nManager()